BEGIN;
CREATE SEQUENCE public.order_number_seq START WITH 1001;
CREATE TABLE public.categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(40) NOT NULL UNIQUE
);
CREATE TABLE public.menu_items (
  item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES public.categories(category_id) ON DELETE RESTRICT,
  name varchar(60) NOT NULL UNIQUE,
  description varchar(200) NOT NULL,
  price numeric(10,2) NOT NULL CHECK (price > 0),
  is_available boolean NOT NULL DEFAULT true
);
CREATE TABLE public.staff_users (
  staff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(40) NOT NULL UNIQUE,
  display_name varchar(40) NOT NULL,
  password_hash varchar(100) NOT NULL,
  role varchar(10) NOT NULL DEFAULT 'staff' CHECK (role IN ('staff', 'manager')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$.{53}$')
);
CREATE TABLE public.orders (
  order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number integer NOT NULL UNIQUE DEFAULT nextval('public.order_number_seq'),
  status_token uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  customer_first_name varchar(50) NOT NULL CHECK (btrim(customer_first_name) <> ''),
  status varchar(10) NOT NULL DEFAULT 'Received' CHECK (status IN ('Received', 'Preparing', 'Ready', 'Collected')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.order_items (
  order_id integer NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  item_id integer NOT NULL REFERENCES public.menu_items(item_id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
  PRIMARY KEY (order_id, item_id)
);
CREATE TABLE public.order_status_history (
  history_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  old_status varchar(10),
  new_status varchar(10) NOT NULL,
  changed_by integer REFERENCES public.staff_users(staff_id) ON DELETE RESTRICT,
  changed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, new_status),
  CHECK (((old_status IS NULL AND new_status = 'Received')
    OR (old_status = 'Received' AND new_status = 'Preparing')
    OR (old_status = 'Preparing' AND new_status = 'Ready')
    OR (old_status = 'Ready' AND new_status = 'Collected')) IS TRUE),
  CHECK ((old_status IS NULL) = (changed_by IS NULL))
);
CREATE VIEW public.order_summary AS
SELECT o.order_id, o.order_number, o.customer_first_name, o.status, o.created_at,
  coalesce(sum(oi.quantity), 0) AS item_count,
  coalesce(sum(oi.quantity * oi.unit_price), 0) AS total_price
FROM public.orders o LEFT JOIN public.order_items oi ON oi.order_id = o.order_id
GROUP BY o.order_id;
CREATE INDEX idx_menu_items_category ON public.menu_items(category_id);
CREATE INDEX idx_order_items_item ON public.order_items(item_id);
CREATE INDEX idx_history_staff ON public.order_status_history(changed_by);
CREATE INDEX idx_orders_status_created ON public.orders(status, created_at DESC);
COMMIT;
